val1 = float(input("enter first val: "))
operator = input("enter operator(+,-,*,/):")
val2 = float(input("enter second val:"))
if operator == '+':
    print(val1+val2)
if operator == '-':
    print(val1-val2)
if operator == '*':
    print(val1*val2)
if operator == '/':
    print(val1/val2)
